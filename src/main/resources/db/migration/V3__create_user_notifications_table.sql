CREATE TABLE user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    type VARCHAR(50) NOT NULL,
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    deep_link TEXT,
    target_type VARCHAR(50),
    target_id BIGINT,
    metadata JSONB,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    is_opened BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT NOW(),
    read_at TIMESTAMPTZ(6),
    opened_at TIMESTAMPTZ(6),
    CONSTRAINT chk_user_notifications_type CHECK (type IN ('MATCH_FINISHED', 'GENERIC'))
);

CREATE INDEX idx_user_notifications_user_created
    ON user_notifications (user_id, created_at DESC);

CREATE INDEX idx_user_notifications_user_is_read
    ON user_notifications (user_id, is_read);

CREATE INDEX idx_user_notifications_target
    ON user_notifications (target_type, target_id);