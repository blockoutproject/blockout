CREATE TABLE followers_projection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(16) NOT NULL,
    entity_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP(6),
    last_update TIMESTAMP(6),
    CONSTRAINT chk_followers_projection_entity_type CHECK (entity_type IN ('TEAM', 'POOL')),
    CONSTRAINT uix_followers_projection_entity_user UNIQUE (entity_type, entity_id, user_id)
);

CREATE INDEX idx_followers_projection_entity ON followers_projection (entity_type, entity_id);
CREATE INDEX idx_followers_projection_user ON followers_projection (user_id);