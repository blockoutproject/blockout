import {
  mkdtemp,
  mkdir,
  readFile,
  readdir,
  rm,
  writeFile,
} from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import { JavaFileGenerator } from '@asyncapi/modelina';

import {
  JAVA_OUTPUT_ROOT,
  JAVA_PACKAGE,
  SOURCE_ROOT,
  parseAsyncApiFile,
} from './event-contract-utils.mjs';

const catalog = path.join(SOURCE_ROOT, 'catalog.json');
await parseAsyncApiFile(catalog);

const temporaryRoot = await mkdtemp(
  path.join(tmpdir(), 'blockout-event-models-'),
);
try {
  const generator = new JavaFileGenerator({
    collectionType: 'List',
    modelType: 'record',
  });
  const models = await generator.generateToFiles(
    pathToFileURL(catalog).href,
    temporaryRoot,
    { packageName: JAVA_PACKAGE },
    true,
  );
  const expected = new Set([
    'ClubDeactivationV2Event',
    'ClubDeactivationV2Payload',
    'ClubProjectionChangedV2Event',
    'ClubProjectionChangedV2Payload',
    'ClubUpsertV2Event',
    'ClubUpsertV2Payload',
    'EventType',
    'MatchFinishedV2Event',
    'MatchFinishedV2Payload',
    'MatchLiveLinkCreatedV2Event',
    'MatchLiveLinkCreatedV2Payload',
    'PoolDeactivationV2Event',
    'PoolDeactivationV2Payload',
    'PoolFollowV2Payload',
    'PoolFollowedV2Event',
    'PoolUnfollowedV2Event',
    'PoolProjectionChangedV2Event',
    'PoolProjectionChangedV2Payload',
    'PoolUpsertV2Event',
    'PoolUpsertV2Payload',
    'TeamDeactivationV2Event',
    'TeamDeactivationV2Payload',
    'TeamFollowV2Payload',
    'TeamFollowedV2Event',
    'TeamUnfollowedV2Event',
    'TeamProjectionChangedV2Event',
    'TeamProjectionChangedV2Payload',
    'TeamUpsertV2Event',
    'TeamUpsertV2Payload',
  ]);
  const generatedNames = new Set(models.map((model) => model.modelName));
  if (
    generatedNames.size !== expected.size ||
    [...expected].some((name) => !generatedNames.has(name))
  ) {
    throw new Error(
      `Unexpected generated event model set: ${[...generatedNames].sort().join(', ')}`,
    );
  }

  await rm(JAVA_OUTPUT_ROOT, { recursive: true, force: true });
  const packageRoot = path.join(JAVA_OUTPUT_ROOT, ...JAVA_PACKAGE.split('.'));
  await mkdir(packageRoot, { recursive: true });
  const generatedFiles = (await readdir(temporaryRoot))
    .filter((name) => name.endsWith('.java'))
    .sort();
  for (const fileName of generatedFiles) {
    const source = await readFile(path.join(temporaryRoot, fileName), 'utf8');
    const normalizedSource = source
      .trim()
      .split('\n')
      .map((line) => line.trimEnd())
      .join('\n');
    const normalized = `// Generated by @asyncapi/modelina 5.10.1 from the Blockout AsyncAPI catalog. Do not edit.\n${normalizedSource}\n`;
    await writeFile(path.join(packageRoot, fileName), normalized);
  }
  console.log(
    `Generated ${generatedFiles.length} Java event models in ${packageRoot}`,
  );
} finally {
  await rm(temporaryRoot, { recursive: true, force: true });
}
