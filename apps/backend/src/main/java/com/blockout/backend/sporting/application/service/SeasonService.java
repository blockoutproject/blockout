package com.blockout.backend.sporting.application.service;

import com.blockout.backend.sporting.application.exception.SportingResourceNotFoundException;
import com.blockout.backend.sporting.application.model.SportingViews;
import com.blockout.backend.sporting.application.model.SportingViews.SeasonView;
import com.blockout.backend.sporting.application.port.SportingStore;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.UUID;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

/** Establishes the one canonical season reused by F01; it never infers lifecycle from a match. */
@Service
@RequiredArgsConstructor
public class SeasonService {
  private final SportingStore store;

  /**
   * Reads the acquisition lifecycle of the canonical F02 season.
   *
   * @param id canonical season identity
   * @return current acquisition lifecycle, without any admission or mutation
   */
  @Transactional(readOnly = true)
  public SportingViews.CollectionSeasonView collectionState(UUID id) {
    return store.collectionSeason(id).orElseThrow(SportingResourceNotFoundException::new);
  }

  /**
   * Locks the same canonical season used by classification and terminal acquisition closure.
   *
   * @param id canonical season identity; caller has already acquired its runtime fence
   * @return current lifecycle held through the caller transaction
   */
  @Transactional(propagation = Propagation.MANDATORY)
  public SportingViews.CollectionSeasonView lockCollectionState(UUID id) {
    store.lockSeason(id);
    return collectionState(id);
  }

  /**
   * Lists the canonical season preparation states without provider discovery.
   *
   * @return complete configuration in newest-first order
   */
  @Transactional(readOnly = true)
  public List<SportingViews.CollectionSeasonView> collectionStates() {
    return store.collectionSeasons();
  }

  /**
   * Reads the current acquisition states required by one collection-configuration read.
   *
   * @param ids distinct canonical seasons; an empty selection returns no states
   * @return current states keyed by their requested canonical identities
   * @throws SportingResourceNotFoundException if a requested season no longer exists
   */
  @Transactional(readOnly = true)
  public Map<UUID, SportingViews.CollectionSeasonView> collectionStates(Set<UUID> ids) {
    Map<UUID, SportingViews.CollectionSeasonView> states = store.collectionSeasons(ids);
    if (!states.keySet().equals(ids)) throw new SportingResourceNotFoundException();
    return states;
  }

  /**
   * Publishes a source change within the caller's already locked open-season transaction.
   *
   * @param id season whose lifecycle and revision were checked before the authorized mutation
   * @param activate whether this mutation launches the season's first qualified source
   * @return updated preparation revision, generated by JPA
   */
  @Transactional(propagation = Propagation.MANDATORY)
  public SportingViews.CollectionSeasonView updatePreparation(UUID id, boolean activate) {
    return store.updatePreparation(id, activate);
  }

  /**
   * Persists terminal acquisition closure inside the already authorized caller transaction.
   *
   * @param id canonical open season held exclusively by the caller
   * @return terminal lifecycle with its native editing revision
   */
  @Transactional(propagation = Propagation.MANDATORY)
  public SportingViews.CollectionSeasonView closeCollectionSeason(UUID id) {
    return store.closeCollectionSeason(id);
  }

  /**
   * Reuses an explicitly qualified sporting year; concurrent creation is protected by uniqueness.
   *
   * @param startYear qualified year within the source contract's safe-integer range
   * @return canonical identity, without reopening or changing acquisition lifecycle
   */
  @Transactional
  public SeasonView getOrCreate(long startYear) {
    return store
        .seasonByYear(startYear)
        .orElseGet(() -> store.createSeason(startYear, startYear + "/" + (startYear + 1)));
  }
}
