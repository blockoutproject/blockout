CREATE TABLE matches
(
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_code     VARCHAR(255) NOT NULL,
  league_code    VARCHAR(255) NOT NULL,
  season         VARCHAR(255) NOT NULL,
  pool_id        BIGINT       NOT NULL,
  team_id_a      BIGINT       NOT NULL,
  team_id_b      BIGINT       NOT NULL,
  match_date     TIMESTAMP(6) NOT NULL,
  live_code      BIGINT,
  score          VARCHAR(255),
  set            VARCHAR(255),
  first_referee  VARCHAR(255),
  second_referee VARCHAR(255),
  venue          VARCHAR(255),
  status         VARCHAR(255) NOT NULL CHECK (status IN ('UPCOMING', 'FINISHED')),
  active         BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at     TIMESTAMP(6),
  last_update    TIMESTAMP(6),
  CONSTRAINT uix_match UNIQUE (
                               match_code,
                               league_code,
                               season
    )
);
