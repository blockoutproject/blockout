CREATE TABLE competition_association
(
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pool_id              BIGINT       NOT NULL,
  team_id              BIGINT       NOT NULL,
  club_id              VARCHAR(255) NOT NULL,
  points               INTEGER      NOT NULL,
  points_penalty       INTEGER      NOT NULL,
  wins                 INTEGER      NOT NULL,
  wins_three_to_zero   INTEGER      NOT NULL,
  wins_three_to_one    INTEGER      NOT NULL,
  wins_three_to_two    INTEGER      NOT NULL,
  losses               INTEGER      NOT NULL,
  losses_zero_to_three INTEGER      NOT NULL,
  losses_one_to_three  INTEGER      NOT NULL,
  losses_two_to_three  INTEGER      NOT NULL,
  won_sets             INTEGER      NOT NULL,
  lost_sets            INTEGER      NOT NULL,
  won_points           INTEGER      NOT NULL,
  lost_points          INTEGER      NOT NULL,
  played               INTEGER      NOT NULL,
  coef_points          FLOAT(53)    NOT NULL,
  coef_sets            FLOAT(53)    NOT NULL,
  active               BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at           TIMESTAMP(6),
  last_update          TIMESTAMP(6),
  CONSTRAINT uix_pool_team UNIQUE (pool_id, team_id)
);
